#!/usr/bin/env python3
"""Compile shared JSON guides to dependency-free runtime Lua; --check detects drift."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def lua(value):
    if isinstance(value,str):
        return '"'+value.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n').replace('\r','\\r').replace('\t','\\t')+'"'
    if isinstance(value,list): return '{'+','.join(lua(item) for item in value)+'}'
    if isinstance(value,dict): return '{'+','.join('['+lua(key)+']='+lua(item) for key,item in value.items())+'}'
    raise ValueError('Unsupported guide value')
def render():
    return '-- Copyright 2026 Mobs. MIT licensed. Generated by scripts/build_guidance.py.\nreturn '+lua({
        'commands':json.loads((ROOT/'config/command_guides.json').read_text()),
        'tutorial':json.loads((ROOT/'config/tutorial.json').read_text()),
    })+'\n'
if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=ROOT/'src/mobs_console/Scripts/command_guides.lua';content=render()
    if args.check:
        if not path.exists() or path.read_text()!=content: raise SystemExit('Guidance data drift; run scripts/build_guidance.py')
    else: path.write_text(content)
