#!/usr/bin/env python3
"""Validate the reference inventory and render the 25-group comparison."""
import argparse
from collections import Counter
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATUSES = {"covered", "partial", "missing", "research"}


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def render():
    inventory = json.loads((ROOT / "config/reference_commands.json").read_text())
    groups = json.loads((ROOT / "config/command_groups.json").read_text())["groups"]
    commands = inventory["commands"]
    names = [row["command"] for row in commands]
    assigned = [name for group in groups for name in group["original_commands"]]
    assert len(groups) == 25, "Expected 25 roadmap groups"
    assert len({group["id"] for group in groups}) == 25, "Duplicate group ID"
    assert len(names) == len(set(names)) == 74, "Original baseline must contain 74 unique identifiers"
    assert Counter(assigned) == Counter(names), "Every original must belong to exactly one group"
    for group in groups:
        for row in commands:
            if row["command"] in group["original_commands"]:
                assert row["group"] == group["id"], "Group membership drift"
    for row in commands:
        assert row["status"] in STATUSES
        assert row["implemented_in_mobs"] == (row["status"] == "covered")
        if row["status"] in {"covered", "partial"}:
            assert row["mobs_equivalent"], "Missing counterpart"
    counts = Counter(row["status"] for row in commands)
    complete_groups = sum(
        all(row["status"] == "covered" for row in commands if row["group"] == group["id"])
        for group in groups
    )
    lines = [
        "# Original mod comparison: 25 useful command groups", "",
        "<!-- Generated by scripts/command_parity.py; edit config/command_groups.json and config/reference_commands.json. -->", "",
        f"Reviewed against Mobs **{inventory['reviewed_mobs_version']}**. Baseline: **{inventory['baseline_version']}**.", "",
        "Evidence: 74 command identifiers observed in the supplied original DLL, not its implementation source. "
        "Scope combines observed help/messages, selected private handler inspection and our independent implementation. "
        "This does not describe an unseen newer paid release. Original `k.*` aliases are not registered by Mobs.", "",
        f"**Practical counterpart coverage: {counts['covered']}/74 ({counts['covered'] / 74:.1%}).** "
        f"Also: {counts['partial']} partial, {counts['missing']} missing, {counts['research']} needing original-behavior research. "
        f"{complete_groups}/25 groups have counterparts for every original identifier in that group.", "",
        "Covered means a practical counterpart exists; it does not mean identical behavior or fully verified gameplay. "
        "Partial entries do not count toward coverage. Gameplay evidence is recorded separately below. "
        "The denominator counts original identifiers, so multiple originals can map to one Mobs command.", "",
        "Priorities are suggestions: P1 = most useful next, P2 = later, P3 = research/developer tooling; Maintain = existing coverage. "
        "All syntax in the Next step column is **proposed**, not currently usable unless explicitly described as existing.", "",
        "## Comparison and roadmap", "",
        "| # | Command group | OG covered / total | Status | Current Mobs commands / scope | Next step | Priority |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for index, group in enumerate(groups, 1):
        rows = [row for row in commands if row["group"] == group["id"]]
        covered = sum(row["status"] == "covered" for row in rows)
        status = "Covered" if covered == len(rows) else (
            "Partial" if any(row["status"] in {"covered", "partial"} for row in rows)
            else "Missing / research" if any(row["status"] == "research" for row in rows)
            else "Missing"
        )
        values = [index, group["title"], f"{covered}/{len(rows)}", status,
                  group["current"], group["next_step"], group["priority"]]
        lines.append("| " + " | ".join(cell(value) for value in values) + " |")
    lines += ["", "## Gameplay evidence, separate from coverage", "",
              "User confirmations are scoped to what was reported. Full variant matrices and save/load persistence are not inferred.", "",
              "| Group | Recorded evidence / remaining verification |", "| --- | --- |"]
    lines += [f"| {cell(group['title'])} | {cell(group['gameplay'])} |" for group in groups]
    lines += ["", "## Exact original-identifier checklist", "",
              "Use this table to close individual gaps without counting an entire group prematurely.", "",
              "| Original identifier | Group | Status | Mobs counterpart | Scope / gap |",
              "| --- | --- | --- | --- | --- |"]
    titles = {group["id"]: group["title"] for group in groups}
    for row in commands:
        values = [f"`{row['command']}`", titles[row["group"]], row["status"],
                  row["mobs_equivalent"] or "—", row["scope_note"]]
        lines.append("| " + " | ".join(cell(value) for value in values) + " |")
    lines += ["", "## Mobs extras outside the 74-command denominator", "",
              "New Supplies placement and empty/selected pile cleanup were confirmed working by the user. "
              "These are goods-pile tools, not OG deposit/resource-node spawning or general building demolition.", "",
              "Other additions include region pinning, inventories and construction diagnostics, guarded undo, "
              "regional perk points/respec/stacking, and tree replanting. The user reported perk commands working; "
              "save/load persistence has not been separately confirmed. Latest forestry changes still await confirmation.", "",
              "## Maintaining the tracker", "",
              "1. Update each original entry in `config/reference_commands.json` with its counterpart, status and scope. "
              "Set `implemented_in_mobs` true only for `covered`.",
              "2. Update priorities, next steps and gameplay evidence in `config/command_groups.json`.",
              "3. Run `python3 scripts/command_parity.py` to regenerate this document, or append `--check` to validate it without writing.",
              "4. Mark coverage only after implementation review; record gameplay results separately. "
              "Expand the baseline only with a newly evidenced original inventory and an explicit version change.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "docs/command_parity.md"
    content = render()
    if args.check:
        if not output.exists() or output.read_text() != content:
            raise SystemExit("Comparison is stale; run python3 scripts/command_parity.py")
        print("Validated: 25 groups, 74 unique originals, statuses and generated comparison current.")
    else:
        output.write_text(content)
        print(output)


if __name__ == "__main__":
    main()
